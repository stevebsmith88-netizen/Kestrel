#!/usr/bin/env python3
"""Builds lib/pay-benchmark-data.ts from the Government of Canada Job Bank wages file (open.canada.ca, "Wages" dataset).

Run once a year, when Job Bank publishes a new file (the 2025 file was revised on 19th November 2025):
  1. Download the newest "Wages" CSV from https://open.canada.ca/data/en/dataset/adad580f-76b0-4502-bd05-20c125de9116
     (the file is served from opencanada.blob.core.windows.net) into an empty folder.
  2. python3 scripts/build-pay-benchmark.py path/to/wages.csv --file-name "2a71-das-wage2025opendata-esdc-all-19nov2025-vf.csv"
  3. npm test, then read the diff before committing. docs/pay-benchmark.md explains the choices.

Only the rows listed in MAPPING are kept. To add a province or a role, add it below, run the script, and read the figures.
"""
import argparse, csv, json, sys

# Kestrel role -> Job Bank occupation (National Occupational Classification 2021 code and the group's name in the file).
# Roles with no entry here have no official figure and fall back to the labelled starting range (see docs/pay-benchmark.md).
# "exact" means the Job Bank group is named for the role. "closest" means Kestrel chose the nearest group, and the form says so.
MAPPING = {
    "Optometrist": ("NOC_31111", "exact"),
    "Optician": ("NOC_32100", "exact"),
    "Optometric assistant or technician": ("NOC_33109", "closest"),
    "Patient care or reception": ("NOC_14101", "closest"),
    "Practice or clinic manager": ("NOC_12010", "closest"),
}
# Province code in the file -> name used on Kestrel.
PROVINCES = {
    "ON": "Ontario", "AB": "Alberta", "BC": "British Columbia", "MB": "Manitoba", "NB": "New Brunswick",
    "NL": "Newfoundland and Labrador", "NS": "Nova Scotia", "PE": "Prince Edward Island", "QC": "Quebec",
    "SK": "Saskatchewan", "NT": "Northwest Territories", "NU": "Nunavut", "YT": "Yukon",
}

COLUMNS = {
    "q1": "Quartile1_Wage_Salaire_Quartile1",
    "median": "Median_Wage_Salaire_Median",
    "q3": "Quartile3_Wage_Salaire_Quartile3",
}

def number(text):
    text = (text or "").strip()
    return float(text) if text else None

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv_path")
    ap.add_argument("--file-name", required=True, help="the file's name on open.canada.ca, recorded in the output")
    ap.add_argument("--out", default="lib/pay-benchmark-data.ts")
    args = ap.parse_args()

    rows = list(csv.DictReader(open(args.csv_path, encoding="utf-8-sig")))
    noc_to_role = {noc: role for role, (noc, _) in MAPPING.items()}
    entries, revision = [], set()
    for r in rows:
        if r["NOC_CNP"] not in noc_to_role or r["prov"] not in PROVINCES:
            continue
        if r["Median_Wage_Salaire_Median"].strip() == "" or r["Source2025_NHQ"].strip() in ("", "N/A"):
            continue
        # The province wide row has a 4 character region code such as ER35. Economic regions inside a province have longer codes.
        if len(r["ER_Code_Code_RE"]) != 4:
            continue
        revision.add(r["Revision_Date_Date_revision"])
        entries.append({
            "role": noc_to_role[r["NOC_CNP"]],
            "province": PROVINCES[r["prov"]],
            "noc": r["NOC_CNP"].replace("NOC_", ""),
            "occupation": r["NOC_Title_eng"],
            "match": dict(MAPPING.values())[r["NOC_CNP"]],
            "basis": "year" if r["Annual_Wage_Flag_Salaire_annuel"].strip() == "1" else "hour",
            **{k: number(r[c]) for k, c in COLUMNS.items()},
            "survey": r["Data_Source_E"].strip() or r["Source2025_NHQ"].strip(),
            "period": r["Reference_Period"].strip(),
        })
    if len(revision) != 1:
        sys.exit(f"Expected one revision date, found {sorted(revision)}")
    entries.sort(key=lambda e: (e["role"], e["province"]))
    expected = len(MAPPING) * len(PROVINCES)
    missing = [(role, prov) for role in MAPPING for prov in PROVINCES.values() if not any(e["role"] == role and e["province"] == prov for e in entries)]
    if missing:
        print(f"{len(entries)} of {expected} role and province pairs have official figures. Without one: {missing}", file=sys.stderr)

    out = f"""// GENERATED by scripts/build-pay-benchmark.py. Do not edit by hand; run the script again with a new file.
// Source: Employment and Social Development Canada, Job Bank "Wages" dataset on open.canada.ca
// (https://open.canada.ca/data/en/dataset/adad580f-76b0-4502-bd05-20c125de9116), file {args.file_name}, revised {sorted(revision)[0]}.
// Licence: Open Government Licence - Canada (https://open.canada.ca/en/open-government-licence-canada). Notes in docs/pay-benchmark.md.

export const JOB_BANK_SOURCE = {{
  name: "Job Bank wages, Employment and Social Development Canada",
  dataset: "https://open.canada.ca/data/en/dataset/adad580f-76b0-4502-bd05-20c125de9116",
  file: {json.dumps(args.file_name)},
  revised: {json.dumps(sorted(revision)[0])},
}} as const;

export type JobBankWage = {{
  role: string;
  province: string;
  noc: string; // National Occupational Classification 2021 code
  occupation: string; // the Job Bank occupation group's name
  match: "exact" | "closest"; // whether the group is named for the role or is the nearest one
  basis: "hour" | "year"; // how Job Bank publishes this occupation
  q1: number | null;
  median: number;
  q3: number | null;
  survey: string;
  period: string; // years the survey figures cover
}};

export const JOB_BANK_WAGES: readonly JobBankWage[] = {json.dumps(entries, indent=2)};
"""
    open(args.out, "w").write(out)
    print(f"Wrote {len(entries)} rows to {args.out}")

main()
